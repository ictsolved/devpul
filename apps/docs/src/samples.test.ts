import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { expect, test } from 'vitest';

const root = join(import.meta.dirname, '../../..');
const files = (dir: string, ext: string) =>
  readdirSync(join(root, dir), { recursive: true, encoding: 'utf8' })
    .filter((f) => f.endsWith(ext))
    .map((f) => join(dir, f));

// Blocks that need an app's generated lib/devpul/plugins.dart; examples/devpul_example and
// contract/app hold real ones.
const skipped = ["import 'devpul/plugins.dart';", '// Generated by devpul from devpul.lock. Do not edit.'];

const lines = (text: string) =>
  text
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && l !== "import 'stubs.dart';");

// Every Dart block in the docs and READMEs is a run of lines, indentation aside, of one file in
// samples/, which dart analyze checks.
const samples = files('apps/docs/samples/lib', '.dart').map((f) => lines(readFileSync(join(root, f), 'utf8')));
const pages = [
  ...files('apps/docs/src/content/docs', '.md'),
  'README.md',
  ...readdirSync(join(root, 'packages')).map((p) => `packages/${p}/README.md`),
];

const contains = (sample: string[], block: string[]) =>
  sample.some((_, i) => block.every((l, j) => sample[i + j] === l));

test.each(pages)('%s', (page) => {
  const text = readFileSync(join(root, page), 'utf8');
  for (const [, code = ''] of text.matchAll(/```dart\n([\s\S]*?)```/g)) {
    const block = lines(code);
    if (skipped.includes(block[0] ?? '')) continue;
    expect(
      samples.some((s) => contains(s, block)),
      `not in apps/docs/samples:\n${code}`,
    ).toBe(true);
  }
});
